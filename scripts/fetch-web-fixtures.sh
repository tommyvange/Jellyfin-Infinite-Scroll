#!/usr/bin/env bash
set -euo pipefail

project_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
requested_version="${1:-}"
fixture_dir="${2:-}"
if [[ "$#" -gt 2 ]]; then
    printf 'Usage: %s [Jellyfin version] [fixture directory]\n' "$0" >&2
    exit 1
fi

# Read pinned production filenames from the same configuration as the CI matrix.
# Reject unknown versions before creating directories or contacting upstream.
fixture_metadata="$(node --input-type=module - "$project_dir/release/config.json" "$requested_version" <<'NODE'
import { readFileSync } from 'node:fs';
const config = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const version = process.argv[3] || config.testedJellyfinVersions.at(-1);
const fixture = config.webFixtures[version];
if (!fixture) throw new Error(`No pinned Jellyfin Web fixtures for ${version}. Add them to release/config.json first.`);
if (!/^\d+\.\d+$/.test(fixture.release)
    || !Array.isArray(fixture.files) || fixture.files.length !== 4
    || fixture.files.some(name => !/^\d+\.[a-f\d]+\.chunk\.js$/.test(name))
    || new Set(fixture.files).size !== fixture.files.length) {
    throw new Error(`Invalid pinned Jellyfin Web fixtures for ${version}.`);
}
console.log(version);
console.log(fixture.release);
console.log(fixture.files.join('\n'));
NODE
)"
metadata_lines=()
while IFS= read -r line; do
    metadata_lines+=("$line")
done <<< "$fixture_metadata"
resolved_version="${metadata_lines[0]}"
release="${metadata_lines[1]}"
files=("${metadata_lines[@]:2}")
fixture_dir="${fixture_dir:-$project_dir/.research/fixtures/$resolved_version}"

mkdir -p "$fixture_dir"
# Patches are generated by the current checkout during verification. A fixture
# cache must never supply output from an earlier plugin revision.
for patched_file in "$fixture_dir"/*.patched.js; do
    [[ -f "$patched_file" ]] && rm -- "$patched_file"
done

# Remove other revisions of these four chunks when reusing a directory for a
# different Jellyfin release; duplicate query/toolbar fixtures would be ambiguous.
for filename in "${files[@]}"; do
    chunk_id="${filename%%.*}"
    for old_file in "$fixture_dir/$chunk_id".*.chunk.js; do
        if [[ -f "$old_file" && "${old_file##*/}" != "$filename" ]]; then
            rm -- "$old_file"
        fi
    done
done

complete=true
for filename in "${files[@]}"; do
    if [[ ! -s "$fixture_dir/$filename" ]]; then
        complete=false
        break
    fi
done
if [[ "$complete" == true ]]; then
    printf 'Using cached Jellyfin %s fixtures in %s\n' "$release" "$fixture_dir"
    exit 0
fi

work_dir="$(mktemp -d)"
trap 'rm -rf "$work_dir"' EXIT
archive_members=()
for filename in "${files[@]}"; do
    archive_members+=("jellyfin/jellyfin-web/$filename")
done

# Official portable archives contain the shipped web assets. Download to a
# temporary archive so a retry cannot concatenate partial streams into tar.
printf 'Fetching pinned Jellyfin %s web fixtures\n' "$release"
curl --fail --location --silent --show-error --retry 3 --retry-delay 2 \
    --connect-timeout 30 \
    --output "$work_dir/portable.tar.gz" \
    "https://repo.jellyfin.org/files/server/portable/stable/v$release/any/jellyfin_$release.tar.gz"
tar -xz -f "$work_dir/portable.tar.gz" -C "$work_dir" --strip-components=2 \
    "${archive_members[@]}"
for filename in "${files[@]}"; do
    if [[ ! -s "$work_dir/$filename" ]]; then
        printf 'Missing or empty upstream fixture: %s\n' "$filename" >&2
        exit 1
    fi
done
for filename in "${files[@]}"; do
    mv -- "$work_dir/$filename" "$fixture_dir/$filename"
done
printf 'Saved four Jellyfin %s fixtures in %s\n' "$release" "$fixture_dir"
